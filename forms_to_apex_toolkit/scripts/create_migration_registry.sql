SET DEFINE OFF

-- One row per Forms module
CREATE TABLE mig_form_registry (
    form_name      VARCHAR2(30)  NOT NULL,          -- ORDERS (= .fmb name, upper case)
    forms_app      VARCHAR2(30),                    -- Forms application / menu (e.g. SALES)
    subsystem      VARCHAR2(60),                    -- APEX Page Group
    app_id         NUMBER        NOT NULL,          -- APEX application id
    page_from      NUMBER        NOT NULL,          -- e.g. 120
    page_to        NUMBER        NOT NULL,          -- main page (f345: child pages = <page>01..<page>09)
    page_alias     VARCHAR2(255) NOT NULL,          -- ORDERS
    package_name   VARCHAR2(30),                    -- ORDERS (f345: package = form name)
    complexity     VARCHAR2(10),                    -- SIMPLE / MEDIUM / COMPLEX
    status         VARCHAR2(20)  DEFAULT 'PLANNED' NOT NULL,
    owner          VARCHAR2(60),                    -- developer
    business_owner VARCHAR2(60),
    notes          VARCHAR2(4000),
    created_on     DATE          DEFAULT SYSDATE NOT NULL,
    updated_on     DATE,
    CONSTRAINT mig_form_reg_pk     PRIMARY KEY (form_name),
    CONSTRAINT mig_form_reg_pg_uk  UNIQUE (app_id, page_from),
    CONSTRAINT mig_form_reg_rng_ck CHECK (page_to >= page_from),
    CONSTRAINT mig_form_reg_cpx_ck CHECK (complexity IN ('SIMPLE', 'MEDIUM', 'COMPLEX')),
    CONSTRAINT mig_form_reg_st_ck  CHECK (status IN ('PLANNED', 'ANALYSIS', 'LOGIC', 'DESIGN',
                                                     'BUILD', 'TEST', 'UAT', 'PROD', 'ON_HOLD'))
);

COMMENT ON TABLE mig_form_registry IS 'Forms -> APEX migration: one row per Forms module (page range, package, status)';

-- One row per Forms object (block, item, trigger, LOV, alert, program unit, global, ...)
CREATE TABLE mig_object_map (
    map_id            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    form_name         VARCHAR2(30)   NOT NULL,
    forms_object_type VARCHAR2(30)   NOT NULL,      -- BLOCK, ITEM, TRIGGER, LOV, RECORD_GROUP,
                                                    -- ALERT, PROGRAM_UNIT, CANVAS, GLOBAL, PARAMETER, MENU_ITEM
    forms_object_name VARCHAR2(400)  NOT NULL,      -- ORDERS.CUSTOMER_ID.WHEN-VALIDATE-ITEM
    apex_comp_type    VARCHAR2(30),                 -- PAGE, REGION, ITEM, IG_COLUMN, VALIDATION, PROCESS,
                                                    -- DYNAMIC_ACTION, BUTTON, LOV, TEXT_MESSAGE, APP_ITEM, AUTH_SCHEME
    apex_comp_name    VARCHAR2(400),                -- CUSTOMER_ID VALIDATION / P120_CUSTOMER_ID (f345 names)
    page_id           NUMBER,
    plsql_member      VARCHAR2(70),                 -- ORDERS.CUSTOMER_ID_VAL
    status            VARCHAR2(20)   DEFAULT 'MAPPED' NOT NULL,
    notes             VARCHAR2(4000),
    created_on        DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT mig_obj_map_pk    PRIMARY KEY (map_id),
    CONSTRAINT mig_obj_map_uk    UNIQUE (form_name, forms_object_type, forms_object_name),
    CONSTRAINT mig_obj_map_fk    FOREIGN KEY (form_name) REFERENCES mig_form_registry (form_name),
    CONSTRAINT mig_obj_map_st_ck CHECK (status IN ('MAPPED', 'DROPPED', 'TODO', 'MANUAL'))
);

CREATE INDEX mig_obj_map_name_ix ON mig_object_map (forms_object_name);

COMMENT ON TABLE mig_object_map IS 'Forms object -> APEX component / PL/SQL member (traceability)';

-- Search by Forms name: where is it in APEX and PL/SQL?
CREATE OR REPLACE VIEW mig_v_where_is AS
SELECT r.form_name,
       r.app_id,
       r.page_alias,
       m.forms_object_type,
       m.forms_object_name,
       m.apex_comp_type,
       m.apex_comp_name,
       NVL(m.page_id, r.page_from) AS page_id,
       m.plsql_member,
       m.status,
       r.status                    AS form_status,
       m.notes
  FROM mig_form_registry r
  JOIN mig_object_map    m ON m.form_name = r.form_name;

