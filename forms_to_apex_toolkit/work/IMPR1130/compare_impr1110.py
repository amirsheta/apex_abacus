"""Compare the code units of IMPR1130 with IMPR1110 (step 01 support).
Usage (from forms_to_apex_toolkit): python3 -I work/IMPR1130/compare_impr1110.py
Writes work/IMPR1130/compare_impr1110.md and work/IMPR1130/units_both.json
"""
import json, html, difflib, collections
import xml.etree.ElementTree as ET

NS = '{http://xmlns.oracle.com/Forms}'


def U(s):
    return html.unescape(html.unescape(s or '')).replace('\r', '')


def load(path):
    fm = ET.parse(path).getroot().find(NS + 'FormModule')
    d = {}
    for t in fm.findall(NS + 'Trigger'):
        d['FORM.' + t.get('Name')] = U(t.get('TriggerText'))
    for b in fm.findall(NS + 'Block'):
        for t in b.findall(NS + 'Trigger'):
            d[b.get('Name') + '.' + t.get('Name')] = U(t.get('TriggerText'))
        for i in b.findall(NS + 'Item'):
            for t in i.findall(NS + 'Trigger'):
                d[b.get('Name') + '.' + i.get('Name') + '.' + t.get('Name')] = U(t.get('TriggerText'))
    for p in fm.findall(NS + 'ProgramUnit'):
        d['PU.' + p.get('Name')] = U(p.get('ProgramUnitText'))
    return d


a = load('forms/IMPR/IMPR1110_fmb.xml')
b = load('forms/IMPR/IMPR1130_fmb.xml')
json.dump({'1110': a, '1130': b}, open('work/IMPR1130/units_both.json', 'w', encoding='utf-8'), ensure_ascii=False)

rows = []
for k in sorted(set(a) | set(b)):
    x, y = a.get(k, ''), b.get(k, '')
    if not x.strip() and not y.strip():
        continue
    if x.strip() == y.strip():
        st, n = 'IDENTICAL', 0
    elif not y.strip():
        st, n = 'ONLY_IMPR1110', len(x.splitlines())
    elif not x.strip():
        st, n = 'ONLY_IMPR1130', len(y.splitlines())
    else:
        st = 'CHANGED'
        n = sum(1 for l in difflib.unified_diff([l.rstrip() for l in x.split('\n')], [l.rstrip() for l in y.split('\n')],
                                                lineterm='', n=0)
                if l[:1] in '+-' and l[:3] not in ('+++', '---'))
    rows.append((st, k, n, len(x.splitlines()) if x.strip() else 0, len(y.splitlines()) if y.strip() else 0))

c = collections.Counter(r[0] for r in rows)
order = {'CHANGED': 0, 'ONLY_IMPR1130': 1, 'ONLY_IMPR1110': 2, 'IDENTICAL': 3}
with open('work/IMPR1130/compare_impr1110.md', 'w', encoding='utf-8') as o:
    o.write('# IMPR1130 vs IMPR1110 - code units compared\n\n')
    o.write('Generated by `work/IMPR1130/compare_impr1110.py` (decoded TriggerText / ProgramUnitText, trailing blanks '
            'ignored). Changed lines = added + removed lines of a unified diff. Counts: ')
    o.write(', '.join('%s %d' % kv for kv in sorted(c.items())) + '.\n')
    o.write('`PU.CG$IMPR1110_PROD_CENTRL_GLOBAL` / `PU.CG$IMPR1130_PROD_CENTRL_GLOBAL` are the same Designer package '
            'named after the form.\n\n')
    o.write('| Status | Unit | Changed lines | Lines IMPR1110 | Lines IMPR1130 |\n|---|---|---|---|---|\n')
    for r in sorted(rows, key=lambda r: (order[r[0]], -r[2], r[1])):
        o.write('| %s | `%s` | %d | %d | %d |\n' % r)
print(dict(c))
