"""Generate the PL/SQL of the IMPR1130 delete check from the Forms code (step 02).

Source : PU CGRI$CHK_IMPORTERS (33 dependent-table checks) and the FRM-40510 branch of IMPORTERS.ON-ERROR
         (constraint name -> message), read from work/IMPR1130/units_both.json
         (written by work/IMPR1130/compare_impr1110.py).
Output : work/IMPR1130/step02/delete_check.sql  (two private members, pasted into the package body by
         work/IMPR1130/step02/build_body.py)
Usage  : python3 -I work/IMPR1130/step02/gen_delete_check.py
"""
import json, re, sys

units = json.load(open('work/IMPR1130/units_both.json', encoding='utf-8'))['1130']
cgri = units['PU.CGRI$CHK_IMPORTERS']
on_error = units['IMPORTERS.ON-ERROR']

MSG = re.compile(r"MSGGETTEXT\(5, 'Cannot delete <p1> while dependent <p2> exists', '([^']*)','([^']*)' \)")

# ---------------------------------------------------------------- CGRI$CHK_IMPORTERS
blocks = re.split(r'/\* Deletion of IMPORTERS prevented if ', cgri)[1:]
checks = []
for b in blocks:
    head = b.split('*/', 1)[0].strip()                       # "AGNTS records exist"
    fk = re.search(r'/\* Foreign key\(s\): ([^*]+?)\s*\*/', b).group(1).strip()
    sel = re.search(r"SELECT\s+'1'\s+FROM\s+(\w+)\s+(\w+)\s+WHERE\s+(.*?);", b, re.S)
    if not sel:
        sys.exit('no cursor in block: ' + head)
    table, alias, where = sel.group(1), sel.group(2), sel.group(3)
    where = re.sub(r'\s+', ' ', where).strip()
    where = re.sub(r'\bP_IMPR_NBR\b', 'p_impr_nbr', where)
    where = re.sub(r'\bP_PORT_CD\b', 'p_port_cd', where)
    m = MSG.search(b)
    if not m:
        sys.exit('no message in block: ' + head)
    checks.append(dict(table=table, alias=alias, where=where, p1=m.group(1), p2=m.group(2), fk=fk))

# ---------------------------------------------------------------- ON-ERROR FRM-40510
branch = on_error.split('IF (err_code = 40510) THEN', 1)
if len(branch) != 2:
    sys.exit('FRM-40510 branch not found in ON-ERROR')
pairs = re.findall(r"constraint_name = '(\w+)'\)\s*THEN\s*Des\$Form_errors\.PUSH\(Des\$Form_errors\.MSGGETTEXT\(5, "
                   r"'Cannot delete <p1> while dependent <p2> exists', '([^']*)','([^']*)' \)", branch[1])

q = lambda s: s.replace("'", "''")
out = []
out.append('''    -- Source: PU CGRI$CHK_IMPORTERS (Designer referential check, called by IMPORTERS.KEY-DELREC with
    -- P_CHECK_BOTH TRUE and by IMPORTERS.PRE-DELETE with FALSE; the flag is not read by the code).
    -- Returns the Forms message of the first dependent table that still has rows, NULL when the delete
    -- is allowed. Generated from the Forms text by work/IMPR1130/step02/gen_delete_check.py (%d checks,
    -- same order). Des$Form_errors.PUSH + RAISE_FAILURE -> the caller raises the returned text.
    FUNCTION CGRI$CHK_IMPORTERS (p_impr_nbr IN NUMBER, p_port_cd IN NUMBER) RETURN VARCHAR2
    IS
        v_found NUMBER;
    BEGIN''' % len(checks))
for c in checks:
    out.append('''        -- %s (%s)
        SELECT COUNT(*) INTO v_found FROM %s %s
         WHERE %s
           AND ROWNUM = 1;
        IF v_found > 0 THEN
            RETURN delete_message('%s', '%s');
        END IF;''' % (c['table'], c['fk'], c['table'].lower(), c['alias'].lower(), c['where'], q(c['p1']), q(c['p2'])))
out.append('''        RETURN NULL;
    END CGRI$CHK_IMPORTERS;
''')
out.append('''    -- Source: IMPORTERS.ON-ERROR, branch FRM-40510 (ORA-02292 child record found on DELETE):
    -- constraint name -> Forms message (%d constraints). Generated by gen_delete_check.py.
    FUNCTION delete_constraint_message (p_constraint IN VARCHAR2) RETURN VARCHAR2
    IS
    BEGIN
        RETURN CASE p_constraint''' % len(pairs))
for name, p1, p2 in pairs:
    out.append("                   WHEN '%s' THEN delete_message('%s', '%s')" % (name, q(p1), q(p2)))
out.append('''               END;
    END delete_constraint_message;
''')
open('work/IMPR1130/step02/delete_check.sql', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('checks', len(checks), 'constraints', len(pairs))
for c in checks:
    print(' ', c['table'], '|', c['where'])
