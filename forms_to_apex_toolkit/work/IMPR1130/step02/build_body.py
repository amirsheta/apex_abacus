"""Build plsql/IMPR1130/impr1130_body.sql (step 02) and run the project checks on the package.

Source : work/IMPR1130/step02/impr1130_body.src.sql (hand-written body) + work/IMPR1130/step02/delete_check.sql
         (generated by gen_delete_check.py from PU CGRI$CHK_IMPORTERS / IMPORTERS.ON-ERROR)
Checks : scripts/parameter_names.py (SQL qualification, private functions in SQL), scripts/forms_apx_helpers.py
         (no local copies of FORMS_APX helpers, unknown FORMS_APX calls), identifier length <= 30 bytes,
         every public member of the spec has a body, no Forms built-ins left in code.
Usage  : python3 -I work/IMPR1130/step02/build_body.py
"""
import os, re, sys, subprocess

ROOT = os.getcwd()
sys.path.insert(0, os.path.join(ROOT, 'scripts'))
import parameter_names
import forms_apx_helpers

SRC = 'work/IMPR1130/step02/impr1130_body.src.sql'
GEN = 'work/IMPR1130/step02/delete_check.sql'
SPEC = 'plsql/IMPR1130/impr1130_spec.sql'
OUT = 'plsql/IMPR1130/impr1130_body.sql'

subprocess.check_call([sys.executable, '-I', 'work/IMPR1130/step02/gen_delete_check.py'], stdout=subprocess.DEVNULL)
src = open(SRC, encoding='utf-8').read()
gen = open(GEN, encoding='utf-8').read()
marker = '-- @@DELETE_CHECK@@\n'
if src.count(marker) != 1:
    sys.exit('marker missing in ' + SRC)
body = src.replace(marker, gen)
open(OUT, 'w', encoding='utf-8').write(body)
spec = open(SPEC, encoding='utf-8').read()

problems = []


def code_only(t):
    t = re.sub(r"'(?:[^']|'')*'", "''", t)
    return re.sub(r'--[^\n]*', '', t)


# 1 public members of the spec have a body (name + kind)
spec_members = re.findall(r'^\s{4}(PROCEDURE|FUNCTION)\s+([A-Z0-9_$#]+)', spec, re.M)
body_members = set(re.findall(r'^\s{4}(?:PROCEDURE|FUNCTION)\s+([A-Za-z0-9_$#]+)\s*(?:\(|IS|RETURN)', body, re.M))
for kind, name in spec_members:
    if name not in body_members:
        problems.append('no body for %s %s' % (kind, name))

# 2 identifiers <= 30 bytes
for name in set(re.findall(r'\b[A-Za-z_][A-Za-z0-9_$#]*\b', code_only(spec + body))):
    if len(name.encode('utf-8')) > 30:
        problems.append('identifier longer than 30 bytes: ' + name)

# 3 Forms built-ins that must not appear in code
for b in ('GO_ITEM', 'GO_BLOCK', 'SET_ITEM_PROPERTY', 'Make_Field_Entrable', 'EXECUTE_QUERY', 'CALL_FORM', 'DO_KEY',
          'NAME_IN', 'SYNCHRONIZE', 'FORMS_DDL', 'DispAlert', 'DispArbMsg', 'SET_BLOCK_PROPERTY', ':SYSTEM.', ':GLOBAL.',
          ':PARAMETER.', 'COMMIT;'):
    if re.search(re.escape(b), code_only(body), re.I):
        problems.append('Forms built-in in code: ' + b)

# 4 parameter naming rule
for member, parameter, line in parameter_names.unqualified_in_sql(spec, body):
    problems.append('unqualified parameter in SQL: %s.%s line %s' % (member, parameter, line))
for member, function, line in parameter_names.private_functions_in_sql(spec, body):
    problems.append('private function in SQL: %s calls %s line %s' % (member, function, line))
for old in re.findall(r'\b(I|IO|O)_[A-Z][A-Z0-9_]*\s+(?:IN|OUT)\b', spec):
    problems.append('mode prefix in a parameter name: ' + old)

# 5 FORMS_APX helpers
try:
    for x in forms_apx_helpers.leftovers(body):
        problems.append('local copy of a FORMS_APX helper: %s' % (x,))
    for x in forms_apx_helpers.unknown_calls(spec + body):
        problems.append('unknown FORMS_APX call: %s' % (x,))
except AttributeError as e:
    problems.append('forms_apx_helpers API: %s' % e)

print('written', OUT, len(body.splitlines()), 'lines; spec', len(spec.splitlines()), 'lines;',
      len(spec_members), 'public members')
for p in problems:
    print('PROBLEM', p)
print('%d problem(s)' % len(problems))
sys.exit(1 if problems else 0)
